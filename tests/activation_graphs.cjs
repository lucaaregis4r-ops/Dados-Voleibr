const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('cbv/export/templates/atlas.js', 'utf8');
const start = source.indexOf('function renderTeamAttack(');
const end = source.indexOf('\nfunction renderTeamReception(', start);
const ctx = { esc:x=>String(x).replaceAll('&','&amp;').replaceAll('<','&lt;'),teamName:x=>x,num:x=>String(x),pct:x=>`${Number(x).toFixed(1)}%`,fmt:x=>String(x),phases:()=>'' };
vm.createContext(ctx);
vm.runInContext(source.slice(start,end),ctx);
const rot = (position, distribution) => ({position, distribution, availability_rallies:80,n_lineup:60,source_match_count:5,confidence:{support_index:60,lineup_share:.75,source_games:5},pass_scenarios:{positive:{identified:false,support_games:3}}});
const out=ctx.renderTeamAttack({}, {distribution_model:[rot(1,[{name:'Ana',weight:.6},{name:'Bia',weight:.4}]),rot(2,[{name:'Ana',weight:.25},{name:'Cris',weight:.75}])]});
assert.match(out,/Comparação entre rotações/);
assert.match(out,/Mapa de participação presumida/);
assert.match(out,/60\.0%/);
assert.match(out,/—/);
assert.match(out,/não significa/);
assert.match(out,/Índice de suporte/);
assert.match(out,/não a chance de acerto/);
const empty=ctx.renderTeamAttack({}, {distribution_model:[]});
assert.doesNotMatch(empty,/Mapa de participação presumida/);
console.log('activation visualizations: OK');
